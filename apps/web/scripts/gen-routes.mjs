#!/usr/bin/env node
// Turns the ported Next.js app tree (src/screens, the old `src/app`) into a react-router route table
// (src/routes.generated.tsx). The product is a static export, so app-router routing runs client-side.
// Re-run after adding/removing a page or layout: `node scripts/gen-routes.mjs`.
import { readdirSync, statSync, writeFileSync, existsSync } from 'node:fs';
import { join, relative } from 'node:path';
import { fileURLToPath } from 'node:url';

const root = fileURLToPath(new URL('../src/screens', import.meta.url));
const out = fileURLToPath(new URL('../src/routes.generated.tsx', import.meta.url));
const SKIP = new Set(['api', 'dev', 'dev-test', 'egress', 'glass-material', 'test-meeting']);
let n = 0;
const imports = [];

function lazy(file) {
  const id = `C${n++}`;
  const rel = './screens/' + relative(root, file).replace(/\\/g, '/').replace(/\.tsx$/, '');
  imports.push(`const ${id} = lazy(() => import(${JSON.stringify(rel)}));`);
  return id;
}

function segment(name) {
  if (/^\(.*\)$/.test(name)) return null; // route group: pathless
  if (/^\[\[\.\.\..+\]\]$/.test(name) || /^\[\.\.\..+\]$/.test(name)) return '*';
  const m = /^\[(.+)\]$/.exec(name);
  return m ? `:${m[1]}` : name;
}

function build(dir, path) {
  const children = [];
  const page = join(dir, 'page.tsx');
  if (existsSync(page)) children.push(`{ index: true, element: <Page c={${lazy(page)}} /> }`);
  for (const name of readdirSync(dir).sort()) {
    const sub = join(dir, name);
    if (!statSync(sub).isDirectory() || SKIP.has(name) || name.startsWith('_')) continue;
    const seg = segment(name);
    const inner = build(sub, seg);
    if (inner) children.push(inner);
  }
  if (!children.length) return null;
  const layout = join(dir, 'layout.tsx');
  const isRoot = dir === root;
  const el = existsSync(layout) && !isRoot ? `element: <Layout c={${lazy(layout)}} />, ` : '';
  const p = path === null || path === undefined ? '' : `path: ${JSON.stringify(path)}, `;
  return `{ ${p}${el}children: [${children.join(', ')}] }`;
}

const tree = build(root, null);
const notFound = existsSync(join(root, 'not-found.tsx')) ? lazy(join(root, 'not-found.tsx')) : null;
const src = `/* eslint-disable */
// GENERATED by scripts/gen-routes.mjs from src/screens. Do not edit by hand.
import { lazy } from 'react';
import type { RouteObject } from 'react-router-dom';
import { Layout, Page } from './lib/next-shim/route-elements';

${imports.join('\n')}

export const routes: RouteObject[] = [
  ${tree},
  ${notFound ? `{ path: '*', element: <Page c={${notFound}} /> },` : ''}
];
`;
writeFileSync(out, src);
console.log(`routes: ${n} modules -> ${relative(process.cwd(), out)}`);
